function norm(text: string) {
  return text
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '')
    .replace(/省|市|自治区|特别行政区|壮族|回族|维吾尔|维吾尔族/g, '')
}

function score(item: Place, query: string) {
  const raw = query.trim()
  const q = norm(raw)
  if (!q) return 0
  const name = norm(item.name)
  const full = item.name.toLowerCase().replace(/\s+/g, '')
  const keys = (item.keywords ?? []).map(norm)
  const sub = norm(item.subtitle)

  if (item.id.startsWith('prov-')) {
    if (name === q || keys.includes(q) || full.includes(raw.toLowerCase())) return 120
    if (keys.some((k) => k === q)) return 118
  }
  if (name === q || keys.includes(q)) return 100
  if (name.startsWith(q) || full.startsWith(raw.toLowerCase())) return 92
  if (keys.some((k) => k.startsWith(q) || q.startsWith(k))) return 88
  if (name.includes(q) || full.includes(q)) return 75
  if (keys.some((k) => k.includes(q) || q.includes(k))) return 70
  if (sub.includes(q)) return 45
  return 0
}

export function provinces() {
  return PLACES.filter((x) => x.id.startsWith('prov-'))
}

/** 地图标注用短省名 */
export function shortName(name: string) {
  return name
    .replace(/特别行政区$/, '')
    .replace(/维吾尔自治区$/, '')
    .replace(/壮族自治区$/, '')
    .replace(/回族自治区$/, '')
    .replace(/自治区$/, '')
    .replace(/省$/, '')
    .replace(/市$/, '')
}

export function search(query: string) {
  const q = query.trim()
  if (!q) return provinces()
  return PLACES.map((item) => ({ item, s: score(item, q) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s || a.item.name.localeCompare(b.item.name, 'zh'))
    .map((x) => x.item)
}
